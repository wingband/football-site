path = "lib/generateArticle.ts"
text = open(path, encoding="utf-8").read()

old = '''  * "이 팀의 첫 골"이라고 쓰려면 그 팀 소속 골 중 실제로 "1번째"로 표시된 골에만 써라.
    그 팀이 이미 앞서 골을 넣었다면 이후 골은 "추가골"/"쐐기골"/"역전골" 등으로 불러라.'''

new = '''  * "이 팀의 첫 골"이라고 쓰려면 그 팀 소속 골 중 실제로 "1번째"로 표시된 골에만 써라.
  * 아래 득점 기록의 각 골 줄 끝 [ ] 안에는 그 골이 선제골/동점골/역전골/추가골 중
    무엇인지 이미 계산되어 있다. "역전골"이라는 표현은 반드시 [ ] 안에 "역전골"이라고
    명시된 골에만 써라 — 그 외의 골에 "역전골"을 붙이면 실제로 없었던 장면을 지어내는
    심각한 오보가 된다. 나머지는 표시된 그대로 "선제골"/"동점골"/"추가골" 같은 표현만
    사용하고, 표시에 없는 상태를 임의로 만들어내지 마라.'''

assert text.count(old) == 1
text = text.replace(old, new)
open(path, "w", encoding="utf-8").write(text)
print("generateArticle.ts 패치 완료")
